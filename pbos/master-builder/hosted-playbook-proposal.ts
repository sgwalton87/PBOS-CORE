import { createHash } from "node:crypto";
import { resolvePinnedPpsDependencies } from "../boot/pps-canon-snapshot-verifier";
import type { FencedPrInput } from "../production-runtime/fenced-playbook-pr-executor";

const repository = "sgwalton87/playbook-platform" as const;
const manifestPath = "docs/PPS/manifest.json";
const missions = {
  "MB03-MISSION-001": { title: "Reproduce isolated Playbook QA", canon: ["PPS-010", "PPS-012"], workflow: ".github/workflows/platform-qa.yml" },
  "MB03-MISSION-002": { title: "RCC-010 Playbook proposal evidence", canon: ["PPS-010", "PPS-014", "PPS-015"], workflow: ".github/workflows/ci.yml" },
} as const;

export const proposalDigest = (content: string) => createHash("sha256").update(content, "utf8").digest("hex");

export async function generateHostedPlaybookProposal(missionId: string, baseSha: string, manifestSha256: string,
  read: (path: string, revision: string) => Promise<string>) {
  if (!Object.hasOwn(missions, missionId) || !/^[a-f0-9]{40}$/.test(baseSha) || !/^[a-f0-9]{64}$/.test(manifestSha256)) {
    throw new Error("Proposal requires a reviewed mission and exact source and Canon pins.");
  }
  const mission = missions[missionId as keyof typeof missions];
  const inputs: { path: string; sha256: string }[] = [];
  const readBounded = async (path: string) => {
    const content = await read(path, baseSha);
    if (!content || Buffer.byteLength(content) > 256 * 1024) throw new Error("Proposal source is missing or oversized.");
    return content;
  };
  const readSource = async (path: string) => {
    const content = await readBounded(path);
    inputs.push({ path, sha256: proposalDigest(content) });
    return content;
  };
  const manifest = await readSource(manifestPath);
  const dependencies = await resolvePinnedPpsDependencies(manifest, manifestSha256, mission.canon,
    file => readBounded(`docs/PPS/${file}`));
  const canon: string[] = [];
  for (const id of mission.canon) {
    const entry = dependencies.find(item => item.id === id)!;
    const path = `docs/PPS/${entry.file}`;
    inputs.push({ path, sha256: entry.sha256 });
    canon.push(`- [${id}](../../${path})`);
  }
  const workflow = await readSource(mission.workflow);
  if (!/^jobs:\s*$/m.test(workflow)) throw new Error("Pinned workflow has no supported jobs block.");
  const scripts = JSON.parse(await readSource("package.json")).scripts ?? {};
  const checks = ["lint", "typecheck", "test", "test:run"].filter(name => typeof scripts[name] === "string");
  if (checks.length === 0) throw new Error("The pinned repository exposes no supported package checks.");
  const workflowRef = `https://github.com/${repository}/blob/${baseSha}/${mission.workflow}`;
  const acceptance = missionId === "MB03-MISSION-001" ? [
    "Use disposable accounts and services. Record app, database and mail-capture origins before opening the browser.",
    "Confirm the browser job runs on the proposed commit. Record the browser, workflow attempt, and artifact links.",
    "Record skipped journeys separately from passing ones. Preserve failed traces and confirm teardown."
  ] : [
    "Record the exact source SHA, proposal SHA, allowed file manifest, and draft pull request URL.",
    "Attach the workflow run and job results for the proposal SHA. Reject results from any other commit.",
    "Record the independent reviewer, disposition, and any unresolved failure. Keep release authorization separate."
  ];
  const content = [`# ${mission.title}`, "", `Source revision: \`${baseSha}\``, "", "## Canon references", "", ...canon,
    "", "## Reproduce and verify", "", `- Inspect the [pinned workflow](${workflowRef}).`,
    ...checks.map(name => `- Repository check: \`npm run ${name}\`.`), ...acceptance.map(step => `- ${step}`),
    "", "## Evidence to retain", "", ...inputs.map(item => `- \`${item.path}\` SHA-256 \`${item.sha256}\``), ""].join("\n");
  const proposal: FencedPrInput = { repository, baseSha, missionId, branch: `pbos/mission-${missionId}`,
    path: `docs/pbos-missions/${missionId}.md`, content, title: `PBOS: ${mission.title}`,
    body: `Generated by the bounded PBOS documentation compiler. Source: ${baseSha}. Content SHA-256: ${proposalDigest(content)}.` };
  return { proposal, contentSha256: proposalDigest(content), provenance: { generator: "pbos.playbook-documentation.v1",
    manifestSha256, inputs, canonDependencies: dependencies } };
}
